CREATE TABLE setor (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    sigla VARCHAR(20) NOT NULL,
    CONSTRAINT uk_setor_sigla UNIQUE (sigla)
);

CREATE TABLE categoria (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    descricao TEXT,
    setor_id BIGINT NOT NULL,
    CONSTRAINT fk_categoria_setor
        FOREIGN KEY (setor_id) REFERENCES setor (id)
);

CREATE INDEX idx_categoria_setor_id ON categoria (setor_id);

CREATE TABLE usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(150) NOT NULL,
    email VARCHAR(255) NOT NULL,
    matricula VARCHAR(30) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    setor_id BIGINT,
    CONSTRAINT uk_usuario_email UNIQUE (email),
    CONSTRAINT ck_usuario_tipo CHECK (tipo IN ('SOLICITANTE', 'TECNICO')),
    CONSTRAINT fk_usuario_setor
        FOREIGN KEY (setor_id) REFERENCES setor (id)
);

CREATE INDEX idx_usuario_setor_id ON usuario (setor_id);

CREATE TABLE chamado (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    titulo VARCHAR(200) NOT NULL,
    descricao TEXT NOT NULL,
    local VARCHAR(200) NOT NULL,
    prioridade VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL,
    data_abertura TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    data_fechamento TIMESTAMP WITHOUT TIME ZONE,
    solucao TEXT,
    solicitante_id BIGINT NOT NULL,
    categoria_id BIGINT NOT NULL,
    tecnico_id BIGINT,
    CONSTRAINT ck_chamado_prioridade CHECK (prioridade IN ('BAIXA', 'MEDIA', 'ALTA')),
    CONSTRAINT ck_chamado_status CHECK (status IN ('ABERTO', 'EM_ATENDIMENTO', 'RESOLVIDO', 'CANCELADO')),
    CONSTRAINT fk_chamado_solicitante
        FOREIGN KEY (solicitante_id) REFERENCES usuario (id),
    CONSTRAINT fk_chamado_categoria
        FOREIGN KEY (categoria_id) REFERENCES categoria (id),
    CONSTRAINT fk_chamado_tecnico
        FOREIGN KEY (tecnico_id) REFERENCES usuario (id)
);

CREATE INDEX idx_chamado_solicitante_id ON chamado (solicitante_id);
CREATE INDEX idx_chamado_categoria_id ON chamado (categoria_id);
CREATE INDEX idx_chamado_tecnico_id ON chamado (tecnico_id);

CREATE TABLE interacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto TEXT NOT NULL,
    data_hora TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    chamado_id BIGINT NOT NULL,
    autor_id BIGINT NOT NULL,
    CONSTRAINT fk_interacao_chamado
        FOREIGN KEY (chamado_id) REFERENCES chamado (id),
    CONSTRAINT fk_interacao_autor
        FOREIGN KEY (autor_id) REFERENCES usuario (id)
);

CREATE INDEX idx_interacao_chamado_id ON interacao (chamado_id);
CREATE INDEX idx_interacao_autor_id ON interacao (autor_id);
